'use strict';

// The only bridge between the window and the launcher's main process.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('launcher', {
  state: () => ipcRenderer.invoke('state'),
  games: (centralUrl) => ipcRenderer.invoke('play:games', centralUrl),
  join: (options) => ipcRenderer.invoke('play:join', options),
  onPlayProgress: (callback) => ipcRenderer.on('play-progress', (event, info) => callback(info)),
  privateServers: (placeId) => ipcRenderer.invoke('private:list', placeId),
  createPrivateServer: (options) => ipcRenderer.invoke('private:create', options),
  redeemPrivateCode: (code) => ipcRenderer.invoke('private:redeem', code),
  privateServerAction: (options) => ipcRenderer.invoke('private:action', options),
  stopClient: () => ipcRenderer.invoke('play:stop'),
  startHosting: (config) => ipcRenderer.invoke('host:start', config),
  stopHosting: () => ipcRenderer.invoke('host:stop'),
  players: () => ipcRenderer.invoke('host:players'),
  startWeb: () => ipcRenderer.invoke('web:start'),
  stopWeb: () => ipcRenderer.invoke('web:stop'),
  checks: () => ipcRenderer.invoke('setup:checks'),
  runSetup: (action) => ipcRenderer.invoke('setup:run', action),
  openFolder: (which) => ipcRenderer.invoke('open:folder', which),
  copy: (text) => ipcRenderer.invoke('clipboard:write', text),
  setServer: (centralUrl) => ipcRenderer.invoke('server:set', centralUrl),
  currentAccount: () => ipcRenderer.invoke('auth:current'),
  signIn: (options) => ipcRenderer.invoke('auth:signin', options),
  signOut: () => ipcRenderer.invoke('auth:signout'),
  getAvatar: () => ipcRenderer.invoke('avatar:get'),
  saveAvatar: (body) => ipcRenderer.invoke('avatar:save', body),
  copyAvatar: () => ipcRenderer.invoke('avatar:copy'),
  guestAvatar: () => ipcRenderer.invoke('avatar:guest'),
  uploadAvatarImage: (bytes, guest) => ipcRenderer.invoke('avatar:upload', { bytes, guest }),
  catalog: (options) => ipcRenderer.invoke('catalog:search', options),
  bundle: (id) => ipcRenderer.invoke('catalog:bundle', id),
  item: (id) => ipcRenderer.invoke('catalog:item', id),
  onlinePlayers: () => ipcRenderer.invoke('players:list'),
  friends: () => ipcRenderer.invoke('friends:list'),
  onServerMoved: (callback) => ipcRenderer.on('server-moved', (event, info) => callback(info)),
  announcements: () => ipcRenderer.invoke('announcements:list'),
  friendAction: (verb, body) => ipcRenderer.invoke('friends:action', { verb, body }),
  people: (search) => ipcRenderer.invoke('people:search', search),
  profile: (userId) => ipcRenderer.invoke('people:profile', userId),
  saveBio: (bio) => ipcRenderer.invoke('profile:bio', bio),
  outfits: () => ipcRenderer.invoke('outfits:list'),
  saveOutfit: (body) => ipcRenderer.invoke('outfits:save', body),
  outfitAction: (id, verb, body) => ipcRenderer.invoke('outfits:action', { id, verb, body }),
  gameThumbnail: (options) => ipcRenderer.invoke('games:thumbnail', options),
  openManage: (centralUrl) => ipcRenderer.invoke('open:manage', centralUrl),
  hostThumbnail: (options) => ipcRenderer.invoke('host:thumbnail', options),
  convertPlace: (options) => ipcRenderer.invoke('place:convert', options),
  installPlace: (file) => ipcRenderer.invoke('place:install', file),
  onLog: (callback) => ipcRenderer.on('log', (event, entry) => callback(entry)),
  onStatusChanged: (callback) => ipcRenderer.on('status-changed', () => callback()),
  downloadFiles: (centralUrl) => ipcRenderer.invoke('files:download', centralUrl),
  installUpdate: () => ipcRenderer.invoke('update:install'),
  checkForUpdates: () => ipcRenderer.invoke('update:check'),
  joinWithCode: (options) => ipcRenderer.invoke('join:code', options),
  onJoinProgress: (callback) => ipcRenderer.on('join-progress', (event, info) => callback(info)),
  onUpdateStatus: (callback) => ipcRenderer.on('update-status', (event, status) => callback(status)),
  onFilesProgress: (callback) => ipcRenderer.on('files-progress', (event, info) => callback(info)),
  openStudio: (centralUrl) => ipcRenderer.invoke('studio:open', centralUrl),
  onStudioProgress: (callback) => ipcRenderer.on('studio-progress', (event, info) => callback(info)),
});
